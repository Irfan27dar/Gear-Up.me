import type { Product } from '@/types';
import { slugify } from '@/lib/utils';

type Seed = Omit<
  Product,
  'id' | 'slug' | 'sku' | 'warrantyMonths' | 'isFeatured' | 'isNew' | 'rating' | 'reviewCount' | 'imageUrl'
> &
  Partial<
    Pick<
      Product,
      'slug' | 'sku' | 'warrantyMonths' | 'isFeatured' | 'isNew' | 'rating' | 'reviewCount' | 'imageUrl'
    >
  >;

let counter = 1000;
function mk(seed: Seed): Product {
  counter += 1;
  const slug = seed.slug ?? slugify(seed.name);
  return {
    warrantyMonths: 24,
    isFeatured: false,
    isNew: false,
    rating: 4.6,
    reviewCount: 0,
    imageUrl: null,
    ...seed,
    id: `prod-${slug}`,
    slug,
    sku: seed.sku ?? `GU-${counter}`,
  };
}

