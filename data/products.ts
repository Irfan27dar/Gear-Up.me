export const productBySlug = (slug: string) => products.find((p) => p.slug === slug);
export const productsByCategory = (slug: string) => products.filter((p) => p.categorySlug === slug);
export const productsByBrand = (slug: string) => products.filter((p) => p.brandSlug === slug);
export const featuredProducts = () => products.filter((p) => p.isFeatured);
export const dealProducts = () =>
  products.filter((p) => p.discountPct > 0).sort((a, b) => b.discountPct - a.discountPct);
export const productsByTag = (tag: string) => products.filter((p) => p.tags.includes(tag));

export function relatedProducts(product: Product, limit = 4): Product[] {
  return products
    .filter((p) => p.slug !== product.slug && p.categorySlug === product.categorySlug)
    .slice(0, limit);
}

export function searchProducts(q: string): Product[] {
  const term = q.trim().toLowerCase();
  if (!term) return [];
  return products.filter(
    (p) =>
      p.name.toLowerCase().includes(term) ||
      p.description.toLowerCase().includes(term) ||
      (p.brandSlug ?? '').includes(term) ||
      p.tags.some((t) => t.includes(term)),
  );
}
